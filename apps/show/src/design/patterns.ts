/** The 8 × 8 bitmap of a preset (unknown names: 50 %). */
export function patternBits(preset: string): readonly number[] {
  return (B as Record<string, readonly number[]>)[preset] ?? B.pct50;
}

/** Whether pixel (`x`, `y`) of a preset's tile is foreground. */
export const patternPixel = (preset: string, x: number, y: number): boolean => ((patternBits(preset)[y & 7]! >> (7 - (x & 7))) & 1) === 1;

/** An SVG data URL of one tile (`cell` px per bitmap pixel) in `fg` / `bg` (`RRGGBB`). */
export function patternDataUrl(preset: string, fg: string, bg: string, cell = 1): string {
  const size = 8 * cell;
  let rects = "";
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) if (patternPixel(preset, x, y)) rects += `<rect x="${x * cell}" y="${y * cell}" width="${cell}" height="${cell}"/>`;
  }
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" shape-rendering="crispEdges"><rect width="${size}" height="${size}" fill="#${bg}"/><g fill="#${fg}">${rects}</g></svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}
