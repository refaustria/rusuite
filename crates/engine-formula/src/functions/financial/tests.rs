//! Known values from the Excel documentation.

use crate::ast::ErrorKind;
use crate::functions::test_support::{close, err};

#[test]
fn annuities() {
    close("=PMT(0.08/12,10,10000)", -1037.0320893591643);
    close("=PMT(0.08/12,10,10000,0,1)", -1030.1643271779772);
    close("=FV(0.06/12,10,-200,-500,1)", 2581.4033740601362);
    close("=PV(0.08/12,240,500)", -59777.14585118777);
    close("=NPER(0.12/12,-100,-1000,10000,1)", 59.67386567429457);
    close("=RATE(48,-200,8000)", 0.0077014724882);
}

#[test]
fn payment_split() {
    close("=IPMT(0.1/12,1,36,8000)", -66.66666666666667);
    close("=IPMT(0.1,3,3,8000)", -292.4471299093656);
    close("=PPMT(0.1/12,1,24,2000)", -75.62318600013237);
    // Interest plus principal is the payment.
    close(
        "=IPMT(0.07,5,12,1000,0,1)+PPMT(0.07,5,12,1000,0,1)-PMT(0.07,12,1000,0,1)",
        0.0,
    );
    assert_eq!(err("=IPMT(0.1,13,12,100)"), ErrorKind::Num);
}

#[test]
fn returns() {
    close("=NPV(0.1,-10000,3000,4200,6800)", 1188.4434123352207);
    close(
        "=IRR({-70000,12000,15000,18000,21000,26000})",
        0.08663094803653,
    );
    close(
        "=IRR({-70000,12000,15000,18000,21000},-0.1)",
        -0.021244848273,
    );
    close(
        "=MIRR({-120000,39000,30000,21000,37000,46000},0.1,0.12)",
        0.12609413036591,
    );
    close("=EFFECT(0.0525,4)", 0.053542667370758);
    close("=NOMINAL(0.053543,4)", 0.05250032);
}

#[test]
fn depreciation() {
    close("=SLN(30000,7500,10)", 2250.0);
    close("=SYD(30000,7500,10,1)", 4090.909090909091);
    close("=DB(1000000,100000,6,1,7)", 186083.33333333334);
    close("=DB(1000000,100000,6,7,7)", 15845.098473848);
    close("=DDB(2400,300,10,2)", 384.0);
    close("=DDB(2400,300,10*365,1)", 1.3150684931506849);
    close("=DDB(2400,300,10,10)", 22.1225472);
}
