#!/usr/bin/env bash
# Regenerates NOTICE (P8-41): the third-party Rust crates and npm packages that ship in Rusuite's apps, grouped by
# licence. Tools: `cargo license` (cargo install cargo-license --locked; 0.7.0) and `pnpm licenses` (built in); see
# docs/setup.md and docs/legal-notes.md. Run after dependency changes; CI does not regenerate it.
# Rust: normal dependencies of every workspace crate on every platform (no dev/build dependencies, no proc macros –
# they run at compile time and are not distributed). npm: production dependencies of the workspace packages.
set -euo pipefail
export PATH="$HOME/.cargo/bin:$PATH"
cd "$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"

command -v cargo-license >/dev/null || { echo "missing cargo-license: cargo install cargo-license --locked" >&2; exit 2; }
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
cargo license --avoid-dev-deps --avoid-build-deps --avoid-proc-macros --json >"$work/rust.json"
pnpm -r licenses list --prod --json >"$work/npm.json"

node - "$work/rust.json" "$work/npm.json" >NOTICE <<'JS'
const fs = require("fs");
const [rustFile, npmFile] = process.argv.slice(2);
const OWN = /github\.com\/refaustria\/rusuite/;
const rust = JSON.parse(fs.readFileSync(rustFile, "utf8")).filter((c) => !OWN.test(c.repository ?? "") && c.license !== undefined);
const npmByLicence = JSON.parse(fs.readFileSync(npmFile, "utf8"));
const npm = Object.entries(npmByLicence).flatMap(([license, pkgs]) =>
  pkgs.filter((p) => !p.name.startsWith("@rusuite/")).flatMap((p) => p.versions.map((v) => ({ name: p.name, version: v, license, url: p.homepage }))),
);
const group = (list) => {
  const m = new Map();
  for (const x of list) {
    const key = x.license || "(no licence field – see the package)";
    if (!m.has(key)) m.set(key, []);
    m.get(key).push(x);
  }
  return [...m.entries()].sort(([a, x], [b, y]) => y.length - x.length || a.localeCompare(b));
};
const out = [];
out.push("Rusuite – third-party notices");
out.push("==============================");
out.push("");
out.push("Rusuite (Calc, Write, Show) is MIT-licensed (see LICENSE). The desktop apps and the web apps include the");
out.push("third-party components below, under their own licences. Each package's licence text is in its source");
out.push("distribution (crates.io / npmjs.com) and repository. Generated by scripts/gen-notice.sh – do not edit by hand.");
out.push("");
out.push("Microsoft, Office, Word, Excel and PowerPoint are trademarks of Microsoft Corporation. Rusuite is an");
out.push("independent project, not affiliated with or endorsed by Microsoft. No fonts are bundled.");
const section = (title, list, fmt) => {
  out.push("");
  out.push(title);
  out.push("-".repeat(title.length));
  for (const [license, items] of group(list)) {
    out.push("");
    out.push(`${license} (${items.length})`);
    for (const x of items.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))) out.push(`  ${fmt(x)}`);
  }
};
section(`Rust crates (${rust.length})`, rust, (c) => `${c.name} ${c.version}${c.repository ? ` – ${c.repository}` : ""}`);
section(`npm packages (${npm.length})`, npm, (p) => `${p.name} ${p.version}${p.url ? ` – ${p.url}` : ""}`);
out.push("");
process.stdout.write(out.join("\n"));
JS
echo "gen-notice: wrote NOTICE ($(grep -c '^  ' NOTICE) components)"
