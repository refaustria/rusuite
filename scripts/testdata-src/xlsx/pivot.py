def fixed(wb):
    """Stable document properties (openpyxl stamps the current time)."""
    import datetime

    t = datetime.datetime(2026, 1, 1)
    wb.properties.created = t
    wb.properties.modified = t
    wb.properties.creator = "Rusuite"
    wb.properties.lastModifiedBy = "Rusuite"


def build(cells):
    wb = Workbook()
    fixed(wb)
    data = wb.active
    data.title = "Data"
    for row in SALES:
        data.append(row)
    pivot = wb.create_sheet("Pivot")
    for ref, v in cells:
        pivot[ref] = v
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


