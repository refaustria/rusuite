def add_pivot(data, definition, records, table):
    """Adds the pivot parts openpyxl cannot write."""
    src = zipfile.ZipFile(io.BytesIO(data))
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for info in src.infolist():
            body = src.read(info.filename)
            if info.filename == "[Content_Types].xml":
                body = body.replace(
                    b"</Types>",
                    (
                        '<Override PartName="/xl/pivotCache/pivotCacheDefinition1.xml" '
                        f'ContentType="{CT}pivotCacheDefinition+xml"/>'
                        '<Override PartName="/xl/pivotCache/pivotCacheRecords1.xml" '
                        f'ContentType="{CT}pivotCacheRecords+xml"/>'
                        '<Override PartName="/xl/pivotTables/pivotTable1.xml" '
                        f'ContentType="{CT}pivotTable+xml"/></Types>'
                    ).encode(),
                )
            elif info.filename == "xl/_rels/workbook.xml.rels":
                body = body.replace(
                    b"</Relationships>",
                    (
                        f'<Relationship Id="rIdPc1" Type="{REL}/pivotCacheDefinition" '
                        'Target="pivotCache/pivotCacheDefinition1.xml"/></Relationships>'
                    ).encode(),
                )
            elif info.filename == "xl/workbook.xml":
                # openpyxl declares the r: prefix per <sheet>, not on the root.
                body = body.replace(
                    b"</workbook>",
                    (
                        f'<pivotCaches><pivotCache xmlns:r="{REL}" cacheId="1" '
                        'r:id="rIdPc1"/></pivotCaches></workbook>'
                    ).encode(),
                )
            z.writestr(info, body)
        for name, text in [
            ("xl/worksheets/_rels/sheet2.xml.rels", SHEET_RELS),
            ("xl/pivotTables/pivotTable1.xml", table),
            ("xl/pivotTables/_rels/pivotTable1.xml.rels", PIVOT_RELS),
            ("xl/pivotCache/pivotCacheDefinition1.xml", definition),
            ("xl/pivotCache/_rels/pivotCacheDefinition1.xml.rels", CACHE_RELS),
            ("xl/pivotCache/pivotCacheRecords1.xml", records),
        ]:
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, text.encode())
    return out.getvalue()


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "testdata/xlsx"
    for name, cells, parts in [
        ("basic", BASIC_CELLS, (BASIC_DEFINITION, BASIC_RECORDS, BASIC_TABLE)),
        ("tabular", TABULAR_CELLS, (TABULAR_DEFINITION, TABULAR_RECORDS, TABULAR_TABLE)),
    ]:
        with open(f"{out}/provisional-pivot-{name}.xlsx", "wb") as f:
            f.write(add_pivot(build(cells), *parts))


if __name__ == "__main__":
    main()
